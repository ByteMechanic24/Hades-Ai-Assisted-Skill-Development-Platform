def _phrase_tokens(phrase: str) -> List[str]:
    """Tokenize a phrase while preserving meaningful words."""

    return [
        token
        for token in re.findall(
            r"\b[a-zA-Z0-9_\-\.\#\+]{2,}\b",
            phrase.lower(),
        )
    ]


def _phrase_match(
    phrase: str,
    title: str,
    description: str,
) -> bool:
    """Checks whether an important phrase occurs in title/content."""

    if not phrase:
        return False

    phrase_clean = " ".join(
        _phrase_tokens(phrase)
    )

    combined = f"{title} {description}".lower()

    return phrase_clean in combined


def _concept_overlap_score(
    concepts: List[str],
    title: str,
    description: str,
) -> float:
    """
    Measures how strongly the resource matches required concepts.

    Title matches receive more importance than description matches.
    """

    if not concepts:
        return 0.0

    title_tokens = _tokenize(title)
    content_tokens = _tokenize(description)

    matched = 0.0
    possible = 0.0

    for concept in concepts:

        concept_tokens = _tokenize(concept)

        if not concept_tokens:
            continue

        possible += 1.0

        title_overlap = concept_tokens.intersection(title_tokens)
        content_overlap = concept_tokens.intersection(content_tokens)

        if title_overlap:
            matched += 1.0

        elif content_overlap:
            matched += 0.5

    if possible == 0:
        return 0.0

    return min(1.0, matched / possible)


def _excluded_concept_penalty(
    concepts: List[str],
    title: str,
    description: str,
) -> float:
    """
    Calculates penalty for resources containing excluded concepts.

    A strong title-level match is penalized more heavily than a passing
    mention inside the description.
    """

    if not concepts:
        return 0.0

    title_tokens = _tokenize(title)
    content_tokens = _tokenize(description)

    penalty = 0.0

    for concept in concepts:

        concept_tokens = _tokenize(concept)

        if not concept_tokens:
            continue

        title_overlap = concept_tokens.intersection(title_tokens)
        content_overlap = concept_tokens.intersection(content_tokens)

        if title_overlap:
            penalty += 0.25

        elif content_overlap:
            penalty += 0.08

    return min(0.50, penalty)


def _educational_quality_score(
    url: str,
    title: str,
    description: str,
    is_youtube_stream: bool,
) -> float:
    """
    Estimates educational quality from deterministic signals.

    This is deliberately conservative. It does not claim that a domain
    is objectively good; it simply rewards common educational indicators.
    """

    text = f"{title} {description}".lower()
    domain = _extract_domain(url)

    score = 0.50

    # Strong educational indicators.
    positive_terms = [
        "lecture",
        "course",
        "lesson",
        "tutorial",
        "introduction",
        "explained",
        "fundamentals",
        "foundations",
        "guide",
        "university",
        "academic",
        "research",
        "textbook",
        "curriculum",
        "class",
    ]

    for term in positive_terms:
        if term in text:
            score += 0.025

    # High-quality educational domains.
    academic_domains = [
        ".edu",
        "apa.org",
        "britannica.com",
        "nature.com",
        "sciencedirect.com",
        "springer.com",
        "jstor.org",
        "nih.gov",
        "ncbi.nlm.nih.gov",
    ]

    if any(
        domain == d or domain.endswith(d)
        for d in academic_domains
    ):
        score += 0.20

    # YouTube needs a different quality signal.
    if is_youtube_stream:
        if any(
            term in text
            for term in [
                "lecture",
                "course",
                "university",
                "professor",
                "introduction",
                "explained",
                "fundamentals",
            ]
        ):
            score += 0.10

    # Penalize obvious entertainment / speech / generic material.
    negative_terms = [
        "full speech",
        "motivation",
        "motivational",
        "podcast",
        "reaction",
        "shorts",
        "short",
        "trailer",
        "news",
        "exam",
    ]

    for term in negative_terms:
        if term in text:
            score -= 0.08

    return max(0.0, min(1.0, score))


def _topic_relevance_score(
    request: TopicResourceDiscoveryRequest,
    title: str,
    description: str,
) -> float:
    """
    Calculates topic relevance.

    Exact topic phrase > title overlap > description overlap.
    """

    topic = request.topic_title.strip()

    if not topic:
        return 0.0

    title_lower = title.lower()
    description_lower = description.lower()
    topic_lower = topic.lower()

    # Strongest signal: exact topic phrase in title.
    if topic_lower in title_lower:
        return 1.0

    # Exact phrase anywhere.
    if topic_lower in description_lower:
        return 0.85

    topic_tokens = _tokenize(
        f"{request.topic_title} "
        f"{request.topic_description or ''}"
    )

    title_tokens = _tokenize(title)
    description_tokens = _tokenize(description)

    if not topic_tokens:
        return 0.5

    title_overlap = len(
        topic_tokens.intersection(title_tokens)
    ) / len(topic_tokens)

    description_overlap = len(
        topic_tokens.intersection(description_tokens)
    ) / len(topic_tokens)

    score = (
        title_overlap * 0.70
        + description_overlap * 0.30
    )

    return max(0.0, min(1.0, score))


def _learner_fit_score(
    request: TopicResourceDiscoveryRequest,
    title: str,
    description: str,
) -> float:
    """
    Measures fit with learner experience and learning preferences.
    """

    text = f"{title} {description}".lower()

    score = 0.5

    experience = (
        request.experience_level or ""
    ).lower()

    if experience == "beginner":

        if any(
            term in text
            for term in [
                "beginner",
                "introduction",
                "intro",
                "basics",
                "fundamentals",
                "foundations",
                "101",
            ]
        ):
            score += 0.30

        if any(
            term in text
            for term in [
                "advanced",
                "expert",
                "deep dive",
                "masterclass",
            ]
        ):
            score -= 0.15

    elif experience == "advanced":

        if any(
            term in text
            for term in [
                "advanced",
                "deep dive",
                "research",
                "masterclass",
                "expert",
            ]
        ):
            score += 0.25

    preferences = [
        preference.lower()
        for preference in request.learning_preferences
    ]

    if preferences:

        if any(
            "video" in preference
            or "visual" in preference
            for preference in preferences
        ):
            if "youtube.com" in text or "lecture" in text:
                score += 0.10

        if any(
            "reading" in preference
            or "read" in preference
            or "article" in preference
            for preference in preferences
        ):
            if any(
                term in text
                for term in [
                    "article",
                    "guide",
                    "documentation",
                    "research",
                ]
            ):
                score += 0.10

    return max(0.0, min(1.0, score))


