def normalize_and_rank_resources(
    raw_results: List[Dict[str, Any]],
    request: TopicResourceDiscoveryRequest,
    is_youtube_stream: bool = False,
    max_resources: int = 5,
    search_plan: Optional[SearchQueryPlan] = None,
) -> List[LearningResource]:
    """
    Normalizes, filters, deduplicates, and ranks resources.

    Ranking strategy:

        Topic relevance              35%
        Required concept alignment   20%
        Educational quality          15%
        Learner fit                  10%
        Provider score               10%
        Preferred domain             10%

    Excluded concepts and domains are applied as penalties.

    The active topic is intentionally weighted more heavily than the
    learner's broader career goal.
    """

    if not raw_results:
        return []

    seen_urls: Set[str] = set()
    normalized: List[LearningResource] = []

    plan = search_plan

    topic_tokens = _tokenize(
        f"{request.topic_title} "
        f"{request.topic_description or ''}"
    )

    goal_tokens = _tokenize(
        request.target_goal
    )

    skill_names = [
        s.skill_name.lower()
        for s in request.current_skills
    ]

    learner_prefs = [
        p.lower()
        for p in request.learning_preferences
    ]

    required_concepts = (
        plan.required_concepts
        if plan
        else []
    )

    excluded_concepts = (
        plan.excluded_concepts
        if plan
        else []
    )

    preferred_domains = (
        plan.preferred_domains
        if plan
        else []
    )

    excluded_domains = (
        plan.excluded_domains
        if plan
        else []
    )

    for item in raw_results:

        url = str(
            item.get("url", "")
        ).strip()

        title = str(
            item.get("title", "")
        ).strip()

        description = str(
            item.get(
                "content",
                item.get("description", ""),
            )
        ).strip()

        try:
            provider_score = float(
                item.get("score", 0.5)
            )
        except (TypeError, ValueError):
            provider_score = 0.5

        if not url or not title:
            continue

        # ---------------------------------------------------------------
        # URL validation
        # ---------------------------------------------------------------

        if (
            is_youtube_stream
            and not is_valid_youtube_url(url)
        ):
            continue

        domain = _extract_domain(url)

        # Hard reject excluded domains.
        if _domain_matches(
            domain,
            excluded_domains,
        ):
            continue

        # ---------------------------------------------------------------
        # Deduplication
        # ---------------------------------------------------------------

        clean_url_key = url.rstrip("/").lower()

        if clean_url_key in seen_urls:
            continue

        seen_urls.add(clean_url_key)

        # ---------------------------------------------------------------
        # Resource metadata
        # ---------------------------------------------------------------

        url_hash = hashlib.sha256(
            url.encode("utf-8")
        ).hexdigest()[:10]

        res_id = (
            f"res-{'yt' if is_youtube_stream else 'gen'}"
            f"-{url_hash}"
        )

        if is_youtube_stream:

            res_type: ResourceType = "video"
            source = "YouTube"

        else:

            res_type = _infer_resource_type(
                url,
                title,
                description,
            )

            source = _infer_source(url)

        # ---------------------------------------------------------------
        # Ranking signals
        # ---------------------------------------------------------------

        topic_score = _topic_relevance_score(
            request,
            title,
            description,
        )

        concept_score = _concept_overlap_score(
            required_concepts,
            title,
            description,
        )

        quality_score = _educational_quality_score(
            url,
            title,
            description,
            is_youtube_stream,
        )

        learner_fit = _learner_fit_score(
            request,
            title,
            description,
        )

        provider_score = max(
            0.0,
            min(
                1.0,
                provider_score,
            ),
        )

        preferred_domain_score = (
            1.0
            if _domain_matches(
                domain,
                preferred_domains,
            )
            else 0.5
        )

        excluded_penalty = _excluded_concept_penalty(
            excluded_concepts,
            title,
            description,
        )

        # ---------------------------------------------------------------
        # Goal overlap
        # ---------------------------------------------------------------

        content_tokens = _tokenize(
            f"{title} {description}"
        )

        goal_overlap = (
            len(
                goal_tokens.intersection(
                    content_tokens
                )
            )
            / max(
                1,
                len(goal_tokens),
            )
        )

        goal_overlap = min(
            1.0,
            goal_overlap,
        )

        # Goal is intentionally weak.
        # Topic relevance must dominate.
        goal_score = goal_overlap * 0.15

        # ---------------------------------------------------------------
        # Skill overlap
        # ---------------------------------------------------------------

        skill_overlap = 0.0

        for skill in skill_names:

            skill_tokens = _tokenize(skill)

            if skill_tokens.intersection(
                content_tokens
            ):
                skill_overlap = 1.0
                break

        # ---------------------------------------------------------------
        # Final weighted relevance
        # ---------------------------------------------------------------

        relevance = (
            topic_score * 0.35
            + concept_score * 0.20
            + quality_score * 0.15
            + learner_fit * 0.10
            + provider_score * 0.10
            + preferred_domain_score * 0.10
            + goal_score * 0.05
            + skill_overlap * 0.05
            - excluded_penalty
        )

        clamped_score = round(
            max(
                0.0,
                min(
                    1.0,
                    relevance,
                ),
            ),
            4,
        )

        # ---------------------------------------------------------------
        # Recommendation reasons
        # ---------------------------------------------------------------

        reasons: List[str] = []

        if topic_score >= 0.85:
            reasons.append(
                "Directly teaches the active roadmap topic"
            )

        elif topic_score >= 0.60:
            reasons.append(
                "Strong coverage of the active roadmap topic"
            )

        if concept_score >= 0.60:
            reasons.append(
                "Matches key concepts identified for this topic"
            )

        if is_youtube_stream:
            reasons.append(
                "Educational video resource"
            )

        elif quality_score >= 0.75:
            reasons.append(
                "High-quality educational reference"
            )

        if preferred_domain_score >= 1.0:
            reasons.append(
                f"Preferred educational source: {domain}"
            )

        if learner_fit >= 0.75:
            reasons.append(
                f"Fits the learner's {request.experience_level or 'current'} level"
            )

        if not reasons:
            reasons.append(
                "Relevant supplementary learning material"
            )

        # ---------------------------------------------------------------
        # Difficulty
        # ---------------------------------------------------------------

        title_lower = title.lower()

        difficulty: ResourceDifficulty

        if any(
            term in title_lower
            for term in [
                "advanced",
                "deep dive",
                "expert",
                "masterclass",
            ]
        ):
            difficulty = "advanced"

        elif any(
            term in title_lower
            for term in [
                "beginner",
                "intro",
                "introduction",
                "basics",
                "fundamentals",
                "101",
            ]
        ):
            difficulty = "beginner"

        else:
            difficulty = "intermediate"

        normalized.append(
            LearningResource(
                resource_id=res_id,
                title=title,
                url=url,
                resource_type=res_type,
                source=source,
                description=(
                    description[:300]
                    if description
                    else None
                ),
                relevance_score=clamped_score,
                difficulty=difficulty,
                estimated_time=_estimate_duration(
                    is_youtube_stream,
                    title,
                ),
                why_recommended=reasons,
            )
        )

    # -------------------------------------------------------------------
    # Final ranking
    # -------------------------------------------------------------------

    normalized.sort(
        key=lambda resource: (
            resource.relevance_score,
            resource.title.lower(),
        ),
        reverse=True,
    )

    return normalized[:max_resources]


# ---------------------------------------------------------------------------
# Tokenization
# ---------------------------------------------------------------------------

def _tokenize(text: str) -> Set[str]:

    words = re.findall(
        r"\b[a-zA-Z0-9_\-\.\#\+]{2,}\b",
        text.lower(),
    )

    stopwords = {
        "and",
        "the",
        "for",
        "with",
        "in",
        "to",
        "of",
        "a",
        "an",
        "on",
        "by",
        "is",
        "or",
        "this",
        "that",
        "from",
        "into",
        "about",
        "how",
        "what",
        "why",
        "your",
        "their",
    }

    return {
        word
        for word in words
        if word not in stopwords
    }


# ---------------------------------------------------------------------------
# Resource classification
# ---------------------------------------------------------------------------

def _infer_resource_type(
    url: str,
    title: str,
    description: str,
) -> ResourceType:

    text = (
        f"{url} "
        f"{title} "
        f"{description}"
    ).lower()

    if (
        "docs." in url
        or "documentation" in text
        or "manual" in text
    ):
        return "documentation"

    if any(
        term in text
        for term in [
            "tutorial",
            "walkthrough",
            "how-to",
            "how to",
        ]
    ):
        return "tutorial"

    if any(
        term in text
        for term in [
            "book",
            "oreilly",
            "manning",
        ]
    ):
        return "book"

    if any(
        term in text
        for term in [
            "course",
            "class",
        ]
    ):
        return "course"

    if (
        "github.com" in url
        or "project" in text
    ):
        return "project"

    return "article"


# ---------------------------------------------------------------------------
# Source classification
# ---------------------------------------------------------------------------

def _infer_source(url: str) -> str:

    domain = _extract_domain(url)

    if "docs.scala-lang.org" in domain:
        return "Scala Documentation"

    if "pekko.apache.org" in domain:
        return "Apache Pekko Docs"

    if "fastapi.tiangolo.com" in domain:
        return "FastAPI Docs"

    if "oreilly.com" in domain:
        return "O'Reilly Media"

    if "github.com" in domain:
        return "GitHub"

    return domain or "Web"


# ---------------------------------------------------------------------------
# Duration estimation
# ---------------------------------------------------------------------------

def _estimate_duration(
    is_video: bool,
    title: str,
) -> Optional[str]:

    if is_video:

        title_lower = title.lower()

        if any(
            term in title_lower
            for term in [
                "crash course",
                "masterclass",
                "full course",
            ]
        ):
            return "30-45 mins"

        if any(
            term in title_lower
            for term in [
                "lecture",
                "full lecture",
            ]
        ):
            return "30-60 mins"

        return "15-20 mins"

    return "10-15 mins read"