class QueryBuilder:
    """
    Deterministic translator from SearchQueryPlan to Tavily-compatible
    search parameters.

    The LLM has already generated the semantic query.
    This class only translates that plan into provider parameters.
    """

    @staticmethod
    def build_youtube_search_parameters(
        plan: SearchQueryPlan,
        request: TopicResourceDiscoveryRequest,
    ) -> Dict[str, Any]:
        """
        Builds Tavily parameters for YouTube discovery.

        We deliberately keep the query exactly as generated by the
        Search Query Agent instead of modifying it here.
        """

        return {
            "query": plan.youtube_query.strip(),
            "include_domains": ["youtube.com"],
            "max_results": RESOURCE_SEARCH_CANDIDATE_COUNT,
            "search_depth": "advanced",
        }

    @staticmethod
    def build_general_search_parameters(
        plan: SearchQueryPlan,
        request: TopicResourceDiscoveryRequest,
    ) -> Dict[str, Any]:
        """
        Builds Tavily parameters for general-web discovery.

        Preferred domains are NOT used as include_domains.

        Why?

        include_domains would restrict Tavily to only those domains and could
        accidentally hide excellent resources from universities or other
        authoritative sources.

        Instead, preferred domains are used by the deterministic ranking layer.
        """

        params: Dict[str, Any] = {
            "query": plan.general_query.strip(),
            "max_results": RESOURCE_SEARCH_CANDIDATE_COUNT,
            "search_depth": "advanced",
        }

        if plan.excluded_domains:
            clean_excluded = [
                _clean_domain(domain)
                for domain in plan.excluded_domains
            ]

            valid_excluded = [
                domain
                for domain in clean_excluded
                if domain
            ]

            if valid_excluded:
                params["exclude_domains"] = valid_excluded[:20]

        return params


