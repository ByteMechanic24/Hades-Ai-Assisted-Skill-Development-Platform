# Number of candidates retrieved from Tavily BEFORE deterministic ranking.
# We want a reasonably large candidate pool so ranking has room to work.
RESOURCE_SEARCH_CANDIDATE_COUNT: int = 20


class ResourceProviderError(Exception):
    """Raised when an external resource provider encounters an unrecoverable error."""

    pass


# ---------------------------------------------------------------------------
# Domain helpers
# ---------------------------------------------------------------------------

def _clean_domain(domain_str: str) -> Optional[str]:
    """Sanitize a domain string."""

    if not domain_str or not isinstance(domain_str, str):
        return None

    d = domain_str.strip().lower()

    d = re.sub(r"^https?://", "", d)
    d = d.split("/")[0]
    d = d.split("?")[0]
    d = d.strip()

    if "." in d and not any(
        c in d
        for c in [
            " ",
            "*",
            ":",
            ";",
            "<",
            ">",
            '"',
            "'",
        ]
    ):
        return d

    return None


def _extract_domain(url: str) -> str:
    """Extract normalized hostname from URL."""

    try:
        parsed = urlparse(url)
        return parsed.netloc.lower().removeprefix("www.")
    except Exception:
        return ""


def _domain_matches(domain: str, candidates: List[str]) -> bool:
    """
    Returns True if the URL domain matches one of the candidate domains.

    Supports subdomains, e.g.
        docs.python.org
    matching:
        python.org
    """

    normalized_domain = domain.lower().removeprefix("www.")

    for candidate in candidates:
        clean = _clean_domain(candidate)

        if not clean:
            continue

        clean = clean.removeprefix("www.")

        if normalized_domain == clean:
            return True

        if normalized_domain.endswith("." + clean):
            return True

    return False


