class TavilySearchClient(ResourceSearchProvider):
    """
    Production Tavily Search API client.
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        api_url: Optional[str] = None,
        timeout: float = 10.0,
    ):
        self.api_key = (
            api_key
            if api_key is not None
            else settings.TAVILY_API_KEY or ""
        )

        self.api_url = api_url or settings.TAVILY_API_URL
        self.timeout = timeout

    def search_youtube(
        self,
        query: str,
        max_results: int = RESOURCE_SEARCH_CANDIDATE_COUNT,
        include_domains: Optional[List[str]] = None,
        exclude_domains: Optional[List[str]] = None,
        search_depth: str = "advanced",
        **kwargs: Any,
    ) -> List[Dict[str, Any]]:

        if not self.api_key:
            raise ResourceProviderError(
                "Tavily API key is not configured."
            )

        payload: Dict[str, Any] = {
            "api_key": self.api_key,
            "query": query,
            "include_domains": include_domains or ["youtube.com"],
            "max_results": max(1, min(20, max_results)),
            "search_depth": search_depth or "advanced",
        }

        if exclude_domains:
            payload["exclude_domains"] = exclude_domains

        return self._execute_search(payload)

    def search_general(
        self,
        query: str,
        max_results: int = RESOURCE_SEARCH_CANDIDATE_COUNT,
        include_domains: Optional[List[str]] = None,
        exclude_domains: Optional[List[str]] = None,
        search_depth: str = "advanced",
        **kwargs: Any,
    ) -> List[Dict[str, Any]]:

        if not self.api_key:
            raise ResourceProviderError(
                "Tavily API key is not configured."
            )

        payload: Dict[str, Any] = {
            "api_key": self.api_key,
            "query": query,
            "max_results": max(1, min(20, max_results)),
            "search_depth": search_depth or "advanced",
        }

        if include_domains:
            payload["include_domains"] = include_domains

        if exclude_domains:
            payload["exclude_domains"] = exclude_domains

        return self._execute_search(payload)

    def _execute_search(
        self,
        payload: Dict[str, Any],
    ) -> List[Dict[str, Any]]:

        try:
            with httpx.Client(timeout=self.timeout) as client:
                response = client.post(
                    self.api_url,
                    json=payload,
                )

                if response.status_code != 200:
                    sanitized_text = self._sanitize(response.text)

                    raise ResourceProviderError(
                        f"Tavily API responded with status "
                        f"{response.status_code}: {sanitized_text}"
                    )

                data = response.json()

                return data.get("results", [])

        except httpx.HTTPError as exc:
            sanitized_err = self._sanitize(str(exc))

            raise ResourceProviderError(
                f"HTTP communication failure with Tavily: "
                f"{sanitized_err}"
            ) from None

    def _sanitize(self, text: str) -> str:

        if self.api_key and self.api_key in text:
            return text.replace(
                self.api_key,
                "[REDACTED_API_KEY]",
            )

        return text


